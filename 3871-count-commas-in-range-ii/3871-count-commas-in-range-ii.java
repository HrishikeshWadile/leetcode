class Solution {
    public long countCommas(long n) {
        long c = 0;

        if (n < 1000) return 0;

        // 1,000 to 999,999 -> 1 comma
        if (n < 1000000)
            return n - 999;

        c += 999000;

        // 1,000,000 to 999,999,999 -> 2 commas
        if (n < 1000000000L)
            return 2 * (n - 999999) + c;

        c += 2 * 999000000L;

        // 1,000,000,000 to 999,999,999,999 -> 3 commas
        if (n < 1000000000000L)
            return 3 * (n - 999999999L) + c;

        c += 3 * 999000000000L;

        // 1,000,000,000,000 to 999,999,999,999,999 -> 4 commas
        if (n < 1000000000000000L)
            return 4 * (n - 999999999999L) + c;

        c += 4 * 999000000000000L;

        // 1,000,000,000,000,000 to 999,999,999,999,999,999 -> 5 commas
        if (n < 1000000000000000000L)
            return 5 * (n - 999999999999999L) + c;

        c += 5 * 999000000000000000L;

        // long max value
        return 6 * (n - 999999999999999999L) + c;
    }
}